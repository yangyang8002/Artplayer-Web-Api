    function detect() {
        var s = null;
        try { s = localStorage.getItem('ap_lang'); } catch (e) {}
        if (s && LANGS[s]) return s;
        var q = new URLSearchParams(location.search).get('lang');
        if (q && LANGS[q]) return q;
        var nav = (navigator.language || 'zh').toLowerCase();
        if (nav.indexOf('ja') === 0) return 'ja';
        if (nav.indexOf('fr') === 0) return 'fr';
        if (nav.indexOf('zh') === 0 && (nav.indexOf('tw') > -1 || nav.indexOf('hant') > -1 || nav.indexOf('hk') > -1)) return 'zhHant';
        return nav.indexOf('en') === 0 ? 'en' : 'zh';
    }

    function t(s) {
        if (lang === 'zh') return s;
        if (s == null) return s;
        var d = LANGS[lang] || LANGS.en;
        if (d[s]) return d[s];
        var pats = PATS_ALL[lang] || [];
        for (var i = 0; i < pats.length; i++) {
            if (pats[i][0].test(s)) return s.replace(pats[i][0], pats[i][1]);
        }
        return s;
    }

    function isSkipped(node) {
        var el = node && node.parentNode;
        while (el && el.nodeType === 1) {
            if (skipNames[el.nodeName]) return true;
            if (el.hasAttribute && el.hasAttribute('data-i18n-skip')) return true;
            el = el.parentNode;
        }
        return false;
    }

    function translateTextNode(node) {
        if (lang === 'zh') return;
        if (isSkipped(node)) return;
        var txt = node.nodeValue;
        if (!txt || !txt.trim()) return;
        var key = txt.trim();
        var rep = t(key);
        if (rep && rep !== txt) {
            node.nodeValue = txt.replace(key, rep);
        }
    }

    var skipNames = { SCRIPT: 1, STYLE: 1, TEXTAREA: 1 };

    function apply(root) {
        root = root || document;
        var walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
        var node;
        while ((node = walker.nextNode())) {
            if (skipNames[node.parentNode && node.parentNode.nodeName]) continue;
            translateTextNode(node);
        }
        /* 翻译所有匹配词典的 placeholder / title / aria-label 属性 */
        root.querySelectorAll && root.querySelectorAll('[placeholder], [title], [aria-label], [data-i18n-ph], [data-i18n-title]').forEach(function (el) {
            if (isSkipped(el)) return;
            var ph = el.getAttribute('placeholder');
            if (ph) el.setAttribute('placeholder', t(ph));
            var ti = el.getAttribute('title');
            if (ti) el.setAttribute('title', t(ti));
            var ar = el.getAttribute('aria-label');
            if (ar) el.setAttribute('aria-label', t(ar));
        });
        if (document.title && LANGS[lang] && LANGS[lang][document.title]) document.title = LANGS[lang][document.title];
    }

    /* 动态渲染的文本自动翻译（非 zh 语言下监听 DOM 变化）
       注意：必须在 30ms 节流后整文档 apply，不能同步遍历每个新增子树 —
       否则会被播放器等持续写 DOM 的页面拖入永不结束的遍历/变更队列。 */
    var obs = null, obsScheduled = false;
    function scheduleApply() {
        if (obsScheduled) return;
        obsScheduled = true;
        setTimeout(function () {
            obsScheduled = false;
            try { apply(document.body); } catch (e) {}
        }, 30);
    }
    function startObserver() {
        if (obs || lang === 'zh' || !window.MutationObserver) return;
        obs = new MutationObserver(function () {
            scheduleApply();
        });
        obs.observe(document.body, { childList: true, subtree: true, characterData: true });
    }

    function setLang(l) {
        lang = LANGS[l] ? l : 'zh';
        try { localStorage.setItem('ap_lang', lang); } catch (e) {}
        document.documentElement.lang = lang;
        apply();
        if (lang !== 'zh') startObserver();
    }

    function init() {
        lang = detect();
        document.documentElement.lang = lang;
        apply();
        if (lang !== 'zh') startObserver();
        return lang;
    }

    var ret = { t: t, apply: apply, setLang: setLang, init: init };
    Object.defineProperty(ret, 'lang', { get: function () { return lang; } });
    return ret;
